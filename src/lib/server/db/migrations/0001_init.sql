-- Ardoise schema, version 1.
--
-- What is deliberately NOT stored in the clear:
--   shop phone numbers  -> phone_hmac (keyed hash, lookup only)
--   PINs                -> pin_hash (scrypt + server pepper)
--   session tokens      -> token_hash (sha256)
--   wallet connections  -> wallet_secret (AES-256-GCM)
--   customer names and phone numbers, payer first names -> *_sealed (AES-256-GCM)

create table shops (
	id uuid primary key,
	name text not null,
	place text not null default '',
	phone_hmac text not null unique,
	pin_hash text not null,
	locale text not null default 'fr',
	wallet_kind text not null default 'none' check (wallet_kind in ('none', 'nwc', 'demo')),
	wallet_secret text,
	wallet_label text,
	wallet_connected_at timestamptz,
	is_demo boolean not null default false,
	created_at timestamptz not null default now()
);

create table sessions (
	token_hash text primary key,
	shop_id uuid not null references shops (id) on delete cascade,
	created_at timestamptz not null default now(),
	expires_at timestamptz not null,
	last_seen_at timestamptz not null default now()
);

create index sessions_shop_idx on sessions (shop_id);

create table customers (
	id uuid primary key,
	shop_id uuid not null references shops (id) on delete cascade,
	name_sealed text not null,
	phone_sealed text,
	pay_token text not null unique,
	credit_limit_xof integer check (credit_limit_xof is null or credit_limit_xof > 0),
	archived_at timestamptz,
	created_at timestamptz not null default now()
);

create index customers_shop_idx on customers (shop_id);

create table invoices (
	id uuid primary key,
	public_id text not null unique,
	shop_id uuid not null references shops (id) on delete cascade,
	customer_id uuid not null references customers (id) on delete cascade,
	amount_xof integer not null check (amount_xof > 0),
	amount_sats integer not null check (amount_sats > 0),
	xof_per_btc double precision not null,
	rate_sources text not null default '',
	wallet_kind text not null,
	bolt11 text not null,
	payment_hash text not null unique,
	preimage text,
	status text not null default 'pending' check (status in ('pending', 'paid', 'expired')),
	payer_name_sealed text,
	created_at timestamptz not null default now(),
	expires_at timestamptz not null,
	paid_at timestamptz,
	last_checked_at timestamptz
);

create index invoices_customer_idx on invoices (customer_id, created_at desc);
create index invoices_open_idx on invoices (status, expires_at) where status <> 'paid';

create table entries (
	-- Generated by the client so a retried or offline-queued submission is idempotent.
	id uuid primary key,
	shop_id uuid not null references shops (id) on delete cascade,
	customer_id uuid not null references customers (id) on delete cascade,
	kind text not null check (kind in ('purchase', 'payment_cash', 'payment_lightning')),
	amount_xof integer not null check (amount_xof > 0),
	label text not null default '',
	-- One Lightning payment can only ever be credited once.
	invoice_id uuid unique references invoices (id) on delete cascade,
	occurred_at timestamptz not null default now(),
	created_at timestamptz not null default now(),
	voided_at timestamptz,
	check ((kind = 'payment_lightning') = (invoice_id is not null))
);

create index entries_customer_idx on entries (customer_id, occurred_at);
create index entries_shop_idx on entries (shop_id);

create table rate_limits (
	key text not null,
	window_start timestamptz not null,
	count integer not null default 0,
	primary key (key, window_start)
);

create table kv (
	key text primary key,
	value jsonb not null,
	updated_at timestamptz not null default now()
);
